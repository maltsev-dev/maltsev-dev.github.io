"""Download the three web fonts the site uses and self-host them.

The site used to pull Anton, Inter and JetBrains Mono from Google Fonts at
runtime: a third-party stylesheet in the critical path, and a request that
leaves the visitor's browser for a third party before a single word is drawn.
Both are avoidable — the faces are open licences, and the whole point of
self-hosting is that the site depends on nothing but its own origin.

Run it, and it rewrites `src/styles/fonts.css` from whatever Google currently
serves. The subsets that come back are kept as separate files with the
unicode-range Google gives them, so the browser still downloads only the
ranges a page actually uses.

    python scripts/fetch-fonts.py

The art face (F18) is a separate job and is not touched here.
"""

import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "static" / "fonts"
CSS_OUT = ROOT / "src" / "styles" / "fonts.css"

# A modern desktop UA is what makes Google serve woff2 with unicode-range
# splitting. The default urllib UA gets a single legacy file per face.
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

GOOGLE_CSS = (
    "https://fonts.googleapis.com/css2"
    "?family=Anton"
    "&family=Inter:wght@300;400;500;600;700"
    "&family=JetBrains+Mono:wght@400;500"
    "&display=swap"
)

# The subsets the site can actually render. Latin covers English and the
# punctuation the design uses; cyrillic is there because the blog posts
# quote Russian sources. Greek and Vietnamese are not used and are dropped
# rather than carried around unused.
KEEP_SUBSETS = {"latin", "latin-ext", "cyrillic", "cyrillic-ext"}


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def parse(css: str):
    """Yield (subset, family, weight, style, url, unicode_range) per face."""
    block_re = re.compile(
        r"/\*\s*([\w-]+)\s*\*/\s*@font-face\s*\{(.*?)\}", re.S
    )
    for subset, body in block_re.findall(css):
        if subset not in KEEP_SUBSETS:
            continue

        def field(name: str) -> str:
            m = re.search(name + r":\s*([^;]+);", body)
            return m.group(1).strip() if m else ""

        url = re.search(r"url\((https://[^)]+\.woff2)\)", body)
        if not url:
            continue

        yield {
            "subset": subset,
            "family": field("font-family").strip("'\""),
            "weight": field("font-weight") or "400",
            "style": field("font-style") or "normal",
            "url": url.group(1),
            "range": field("unicode-range"),
        }


def slug(family: str, weight: str, subset: str) -> str:
    return f"{family.lower().replace(' ', '-')}-{weight}-{subset}.woff2"


def main() -> int:
    css = fetch(GOOGLE_CSS).decode("utf-8")
    faces = list(parse(css))
    if not faces:
        print("no faces parsed — the CSS format changed?", file=sys.stderr)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    blocks = []
    seen = set()
    for face in faces:
        name = slug(face["family"], face["weight"], face["subset"])
        if name in seen:
            continue
        seen.add(name)

        target = OUT_DIR / name
        if not target.exists():
            target.write_bytes(fetch(face["url"]))
            print(f"fetched {name} ({target.stat().st_size // 1024} KB)")

        blocks.append(
            "@font-face {\n"
            f"  font-family: '{face['family']}';\n"
            f"  font-style: {face['style']};\n"
            f"  font-weight: {face['weight']};\n"
            "  font-display: swap;\n"
            f"  src: url('/fonts/{name}') format('woff2');\n"
            f"  unicode-range: {face['range']};\n"
            "}"
        )

    header = (
        "/* Self-hosted web fonts.\n"
        " *\n"
        " * Generated by scripts/fetch-fonts.py — edit that script, not this file.\n"
        " *\n"
        " * These were served from Google Fonts at runtime, which meant a\n"
        " * third-party stylesheet sat in the critical path of every page and\n"
        " * every visitor's browser talked to a third party before the first word\n"
        " * was drawn. The faces are open licences; the site now ships its own.\n"
        " *\n"
        " * The unicode-ranges are Google's, so the browser still downloads only\n"
        " * the ranges a page actually renders: an English page never touches the\n"
        " * cyrillic files.\n"
        " */\n\n"
    )

    CSS_OUT.write_text(header + "\n\n".join(blocks) + "\n", encoding="utf-8")
    print(f"wrote {CSS_OUT.relative_to(ROOT)} with {len(blocks)} faces")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
